"""
Step 6 — Streamlit chat UI on top of the FastAPI backend.

Local (outside Docker): run with (in a separate terminal from the FastAPI
server, which must already be running via `uvicorn app:app --reload`):

    streamlit run streamlit_app.py

In Docker Compose: API_URL is set via environment to the 'api' service name
(see docker-compose.yml) instead of localhost, since containers reach each
other by service name, not localhost.
"""

import os

import requests
import streamlit as st

API_URL = os.getenv("API_URL", "http://127.0.0.1:8000")

st.set_page_config(page_title="Crime Text-to-SQL Assistant", page_icon="🔎")
st.title("🔎 Malaysia Crime Text-to-SQL Assistant")
st.caption(
    "Ask questions about crime, income, and population data by district. "
    "SQL is generated by Claude and validated before it runs."
)

if "history" not in st.session_state:
    st.session_state.history = []  # list of dicts: {question, sql, columns, rows, error}

# --- render existing conversation ---
for turn in st.session_state.history:
    with st.chat_message("user"):
        st.write(turn["question"])
    with st.chat_message("assistant"):
        if turn.get("error"):
            st.error(turn["error"])
        else:
            with st.expander("Generated SQL"):
                st.code(turn["sql"], language="sql")
            if turn["rows"]:
                st.dataframe(
                    {col: [row[i] for row in turn["rows"]] for i, col in enumerate(turn["columns"])}
                )
                st.caption(f"{turn['row_count']} row(s)")
            else:
                st.write("No rows returned.")

# --- input box ---
question = st.chat_input("e.g. total crimes per state, excluding the national total")

if question:
    with st.chat_message("user"):
        st.write(question)

    with st.chat_message("assistant"):
        with st.spinner("Generating and running SQL..."):
            try:
                resp = requests.post(f"{API_URL}/query", json={"question": question}, timeout=30)
            except requests.exceptions.ConnectionError:
                error = (
                    "Could not reach the API at "
                    f"{API_URL}. Is `uvicorn app:app --reload` running in another terminal?"
                )
                st.error(error)
                st.session_state.history.append({"question": question, "error": error})
                st.stop()

        if resp.status_code != 200:
            error = f"API error ({resp.status_code}): {resp.json().get('detail', resp.text)}"
            st.error(error)
            st.session_state.history.append({"question": question, "error": error})
        else:
            data = resp.json()
            with st.expander("Generated SQL"):
                st.code(data["sql"], language="sql")
            if data["rows"]:
                st.dataframe(
                    {col: [row[i] for row in data["rows"]] for i, col in enumerate(data["columns"])}
                )
                st.caption(f"{data['row_count']} row(s)")
            else:
                st.write("No rows returned.")
            st.session_state.history.append(data)