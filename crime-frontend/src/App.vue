<script setup>
import { ref, nextTick, onMounted } from 'vue'

const API_URL = import.meta.env.VITE_API_URL || 'http://localhost:8000'

const question = ref('')
const messages = ref([])
const loading = ref(false)
const chatEnd = ref(null)

const examples = [
  'Total crimes per state, excluding the national total',
  'Top 5 districts by crime count',
  "What's the crime trend by year",
]

async function scrollToEnd() {
  await nextTick()
  chatEnd.value?.scrollIntoView({ behavior: 'smooth' })
}

async function ask(text) {
  const q = (text ?? question.value).trim()
  if (!q || loading.value) return

  messages.value.push({ role: 'user', text: q })
  question.value = ''
  loading.value = true
  scrollToEnd()

  try {
    const res = await fetch(`${API_URL}/query`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ question: q }),
    })
    const data = await res.json()

    if (!res.ok) {
      messages.value.push({ role: 'error', text: data.detail || 'Something went wrong.' })
    } else {
      messages.value.push({
        role: 'assistant',
        sql: data.sql,
        columns: data.columns,
        rows: data.rows,
        rowCount: data.row_count,
      })
    }
  } catch (err) {
    messages.value.push({
      role: 'error',
      text: `Could not reach the API at ${API_URL}. Is it running?`,
    })
  } finally {
    loading.value = false
    scrollToEnd()
  }
}

function handleEnter(e) {
  if (!e.shiftKey) {
    e.preventDefault()
    ask()
  }
}
</script>

<template>
  <div class="app">
    <header class="header">
      <div class="header-inner">
        <div class="brand">
          <span class="brand-icon">🔎</span>
          <div>
            <h1>Crime Text-to-SQL</h1>
            <p>Malaysia crime, income &amp; population data by district</p>
          </div>
        </div>
      </div>
    </header>

    <main class="chat">
      <div class="chat-inner">
        <div v-if="messages.length === 0" class="empty-state">
          <p class="empty-title">Ask a question about the data</p>
          <p class="empty-sub">SQL is generated by Claude and validated before it runs.</p>
          <div class="examples">
            <button
              v-for="ex in examples"
              :key="ex"
              class="example-chip"
              @click="ask(ex)"
            >
              {{ ex }}
            </button>
          </div>
        </div>

        <div
          v-for="(m, i) in messages"
          :key="i"
          class="message"
          :class="`message--${m.role}`"
        >
          <template v-if="m.role === 'user'">
            <div class="bubble bubble--user">{{ m.text }}</div>
          </template>

          <template v-else-if="m.role === 'error'">
            <div class="bubble bubble--error">⚠️ {{ m.text }}</div>
          </template>

          <template v-else>
            <div class="bubble bubble--assistant">
              <details class="sql-block">
                <summary>Generated SQL</summary>
                <pre><code>{{ m.sql }}</code></pre>
              </details>

              <div v-if="m.rows.length" class="table-wrap">
                <table>
                  <thead>
                    <tr>
                      <th v-for="col in m.columns" :key="col">{{ col }}</th>
                    </tr>
                  </thead>
                  <tbody>
                    <tr v-for="(row, ri) in m.rows" :key="ri">
                      <td v-for="(val, ci) in row" :key="ci">{{ val }}</td>
                    </tr>
                  </tbody>
                </table>
                <p class="row-count">{{ m.rowCount }} row{{ m.rowCount === 1 ? '' : 's' }}</p>
              </div>
              <p v-else class="row-count">No rows returned.</p>
            </div>
          </template>
        </div>

        <div v-if="loading" class="message message--assistant">
          <div class="bubble bubble--assistant bubble--loading">
            <span class="dot"></span><span class="dot"></span><span class="dot"></span>
          </div>
        </div>

        <div ref="chatEnd"></div>
      </div>
    </main>

    <footer class="composer">
      <div class="composer-inner">
        <textarea
          v-model="question"
          placeholder="e.g. total crimes per state, excluding the national total"
          rows="1"
          @keydown.enter="handleEnter"
        ></textarea>
        <button class="send-btn" :disabled="!question.trim() || loading" @click="ask()">
          ↑
        </button>
      </div>
    </footer>
  </div>
</template>

